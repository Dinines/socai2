"""Transport-independent use-case ports consumed by external HTTP routes.

No sessions, SQL, workers, or model gateways are part of this surface.
"""

from typing import Protocol
from uuid import UUID

from investigation_http.contracts import Actor


class CaseOperations(Protocol):
    async def update_page_data(self, tenant_id, case_id, request, *, actor): ...
    async def publish_evidence(self, tenant_id, case_id, request, *, actor): ...
    async def read_page_data(self, tenant_id, case_id): ...
    async def create_case(self, tenant_id: UUID, request, *, actor: Actor): ...
    async def associate(self, tenant_id, case_id, request, *, actor): ...
    async def move_members(self, tenant_id, case_id, request, *, actor): ...
    async def change_members(self, tenant_id, case_id, request, *, actor): ...
    async def start_case(self, tenant_id, case_id, run_id, request, *, actor): ...
    async def prepare_baseline(self, tenant_id, case_id, request, *, actor): ...
    async def read_cases(self, tenant_id, query): ...
    async def read_case(self, tenant_id, case_id): ...
    async def read_history(self, tenant_id, case_id, *, limit=20, cursor=None): ...
    async def read_run(self, tenant_id, case_id, run_id): ...
    async def read_result(self, tenant_id, case_id, result_id): ...
    async def read_artifact(self, tenant_id, case_id, run_id, artifact_id): ...
    async def read_activities(self, tenant_id, case_id, *, limit=50, offset=0): ...
    async def read_frozen_material(self, tenant_id, case_id, run_id, material_id): ...
    async def read_management(self, tenant_id, case_id): ...
    async def manage_case(self, tenant_id, case_id, request, actor, *, action): ...


class TaskOperations(Protocol):
    async def write(self, tenant_id, case_id, request, *, actor, task_id=None): ...
    async def read(self, tenant_id, case_id, task_id): ...
    async def list(self, tenant_id, case_id, *, limit=20, offset=0): ...
    async def revisions(self, tenant_id, case_id, task_id, *, limit=20, offset=0): ...
    async def read_revision(self, tenant_id, case_id, task_id, revision_id): ...


class AnalysisReads(Protocol):
    async def read_page(self, tenant, kind, identity, **kwargs): ...
    async def read_entry(self, tenant, kind, identity, run_id): ...


class PageReads(Protocol):
    async def read(self, tenant, kind, identity, method, **kwargs): ...


class SubjectManagement(Protocol):
    async def apply(
        self, tenant_id, kind, targets, changes, operation_key, actor, *, feedback=False
    ): ...


class StageExecution(Protocol):
    async def execute(
        self, tenant_id, kind, identity, operation_key, *, requested_by
    ): ...


class ListExports(Protocol):
    async def read(self, tenant_id, kind, query): ...


class GroupingReads(Protocol):
    async def read(self, tenant_id, query): ...


class CaseComments(Protocol):
    async def create(self, tenant_id, case_id, request, *, actor): ...
    async def list(self, tenant_id, case_id, *, limit=20, offset=0): ...
